-- =====================================================================
-- SISTEMA DE CONTRATACION PUBLICA POR FASES - AIL E.P.
-- Script PostgreSQL 16 - Entrega B (v2)
-- Requisito: la tabla "users" ya existe (la crea Laravel).
-- Convenciones: tablas/columnas en espanol, snake_case, sin prefijos.
-- Excepciones de framework: users, created_at, updated_at, deleted_at.
-- =====================================================================
BEGIN;

-- ---------------------------------------------------------------------
-- 1. SEGURIDAD Y ADMINISTRACION
-- ---------------------------------------------------------------------
CREATE TABLE roles (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      varchar(50)  NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9_]+$'),
    nombre      varchar(120) NOT NULL,
    descripcion text,
    es_sistema  boolean NOT NULL DEFAULT false,
    activo      boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE permisos (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              varchar(80)  NOT NULL UNIQUE CHECK (codigo ~ '^[a-z_]+\.[a-z_]+$'),
    nombre              varchar(150) NOT NULL,
    descripcion         text,
    modulo              varchar(50)  NOT NULL,
    requiere_asignacion boolean NOT NULL DEFAULT false,
    activo              boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE rol_permiso (
    rol_id     bigint NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permiso_id bigint NOT NULL REFERENCES permisos(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE usuario_rol (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rol_id  bigint NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, rol_id)
);

CREATE TABLE parametros (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave       varchar(80) NOT NULL UNIQUE,
    valor       text NOT NULL,
    tipo        varchar(20) NOT NULL CHECK (tipo IN ('entero','decimal','texto','booleano')),
    descripcion text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE auditoria (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            bigint REFERENCES users(id),
    evento             varchar(100) NOT NULL,
    entidad            varchar(80),
    entidad_id         bigint,
    valores_anteriores jsonb,
    valores_nuevos     jsonb,
    ip                 varchar(45),
    agente             text,
    created_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX auditoria_entidad_idx ON auditoria (entidad, entidad_id);
CREATE INDEX auditoria_user_idx    ON auditoria (user_id, created_at);

-- ---------------------------------------------------------------------
-- 2. CATALOGOS DE FLUJO
-- ---------------------------------------------------------------------
CREATE TABLE fases (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     varchar(50)  NOT NULL UNIQUE,
    nombre     varchar(120) NOT NULL,
    orden      smallint NOT NULL,
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE rol_fase (
    rol_id  bigint NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    fase_id bigint NOT NULL REFERENCES fases(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, fase_id)
);

CREATE TABLE estados_macro (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     varchar(50)  NOT NULL UNIQUE,
    nombre     varchar(120) NOT NULL,
    orden      smallint NOT NULL,
    fase_id    bigint REFERENCES fases(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE etapas (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fase_id    bigint NOT NULL REFERENCES fases(id),
    codigo     varchar(60)  NOT NULL UNIQUE,
    nombre     varchar(150) NOT NULL,
    orden      smallint NOT NULL,
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE actividades (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etapa_id   bigint NOT NULL REFERENCES etapas(id),
    codigo     varchar(80)  NOT NULL UNIQUE,
    nombre     varchar(200) NOT NULL,
    tipo       varchar(20)  NOT NULL CHECK (tipo IN ('tarea','subproceso','decision')),
    orden      smallint NOT NULL DEFAULT 0,
    rol_id     bigint REFERENCES roles(id),
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE estados_proceso (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     varchar(50)  NOT NULL UNIQUE,
    nombre     varchar(120) NOT NULL,
    orden      smallint NOT NULL,
    es_inicial boolean NOT NULL DEFAULT false,
    es_final   boolean NOT NULL DEFAULT false,
    permite_asignar_codigo boolean NOT NULL DEFAULT false,  -- estados en los que Compras genera el codigo del proceso
    color      varchar(20),
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE estados_documento (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     varchar(50)  NOT NULL UNIQUE,
    nombre     varchar(120) NOT NULL,
    orden      smallint NOT NULL,
    grupo      varchar(20)  NOT NULL CHECK (grupo IN ('pendiente','en_correccion','aprobado','anulado')),
    es_inicial boolean NOT NULL DEFAULT false,
    es_final   boolean NOT NULL DEFAULT false,
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE estados_oferta (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     varchar(50)  NOT NULL UNIQUE,
    nombre     varchar(120) NOT NULL,
    orden      smallint NOT NULL,
    resultado  varchar(20)  NOT NULL CHECK (resultado IN ('en_curso','favorable','desfavorable')),
    es_inicial boolean NOT NULL DEFAULT false,
    es_final   boolean NOT NULL DEFAULT false,
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tipos_proceso (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     varchar(60)  NOT NULL UNIQUE,
    nombre     varchar(150) NOT NULL,
    prefijo    varchar(10)  NOT NULL CHECK (prefijo ~ '^[A-Z0-9]+$'),  -- inicia el codigo del proceso: PE-AILEP-2026-001
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tipos_designacion (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       varchar(60)  NOT NULL UNIQUE,
    nombre       varchar(150) NOT NULL,
    monto_minimo numeric(16,2) NOT NULL DEFAULT 0 CHECK (monto_minimo >= 0),
    orden        smallint NOT NULL DEFAULT 0,
    activo       boolean NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tipos_documento (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                varchar(80)  NOT NULL UNIQUE,
    nombre                varchar(200) NOT NULL,
    fase_id               bigint REFERENCES fases(id),
    etapa_id              bigint REFERENCES etapas(id),
    rol_generador_id      bigint REFERENCES roles(id),
    rol_revisor_id        bigint REFERENCES roles(id),
    requiere_revision     boolean NOT NULL DEFAULT true,
    requiere_aprobacion   boolean NOT NULL DEFAULT true,
    requiere_legalizacion boolean NOT NULL DEFAULT false,
    extensiones_permitidas varchar(100) NOT NULL DEFAULT 'pdf,doc,docx',
    tamano_maximo_mb      integer NOT NULL DEFAULT 20 CHECK (tamano_maximo_mb > 0),
    activo                boolean NOT NULL DEFAULT true,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now()
);

-- Transiciones (una tabla por ambito: proceso, documento, oferta)
CREATE TABLE transiciones_proceso (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_origen_id         bigint REFERENCES estados_proceso(id),
    estado_destino_id        bigint NOT NULL REFERENCES estados_proceso(id),
    codigo                   varchar(60)  NOT NULL,
    nombre                   varchar(150) NOT NULL,
    estado_macro_destino_id  bigint REFERENCES estados_macro(id),
    permiso_id               bigint NOT NULL REFERENCES permisos(id),
    requiere_comentario      boolean NOT NULL DEFAULT false,
    validaciones             jsonb   NOT NULL DEFAULT '{}'::jsonb,
    activo                   boolean NOT NULL DEFAULT true,
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX transiciones_proceso_uq
    ON transiciones_proceso (COALESCE(estado_origen_id, 0), codigo);

-- Requisitos documentales configurables por transicion
CREATE TABLE transicion_proceso_requisitos (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transicion_id               bigint NOT NULL REFERENCES transiciones_proceso(id) ON DELETE CASCADE,
    tipo_documento_id           bigint NOT NULL REFERENCES tipos_documento(id),
    estado_documento_minimo_id  bigint NOT NULL REFERENCES estados_documento(id),
    UNIQUE (transicion_id, tipo_documento_id)
);

CREATE TABLE transiciones_documento (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_origen_id    bigint REFERENCES estados_documento(id),
    estado_destino_id   bigint NOT NULL REFERENCES estados_documento(id),
    codigo              varchar(60)  NOT NULL,
    nombre              varchar(150) NOT NULL,
    permiso_id          bigint NOT NULL REFERENCES permisos(id),
    requiere_comentario boolean NOT NULL DEFAULT false,
    validaciones        jsonb NOT NULL DEFAULT '{}'::jsonb,
    activo              boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX transiciones_documento_uq
    ON transiciones_documento (COALESCE(estado_origen_id, 0), codigo);

CREATE TABLE transiciones_oferta (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_origen_id    bigint REFERENCES estados_oferta(id),
    estado_destino_id   bigint NOT NULL REFERENCES estados_oferta(id),
    codigo              varchar(60)  NOT NULL,
    nombre              varchar(150) NOT NULL,
    permiso_id          bigint NOT NULL REFERENCES permisos(id),
    requiere_comentario boolean NOT NULL DEFAULT false,
    activo              boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX transiciones_oferta_uq
    ON transiciones_oferta (COALESCE(estado_origen_id, 0), codigo);

-- ---------------------------------------------------------------------
-- 3. PROCESOS Y ASIGNACIONES
-- ---------------------------------------------------------------------
CREATE TABLE procesos (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           varchar(40) UNIQUE,   -- lo asigna Compras antes de publicar
    tipo_proceso_id  bigint NOT NULL REFERENCES tipos_proceso(id),
    descripcion_producto text NOT NULL,
    codigo_cpc       varchar(20),
    estado_macro_id  bigint NOT NULL REFERENCES estados_macro(id),
    estado_proceso_id bigint NOT NULL REFERENCES estados_proceso(id),
    ciclo            smallint NOT NULL DEFAULT 1 CHECK (ciclo >= 1),
    observacion      text,
    creado_por       bigint NOT NULL REFERENCES users(id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    deleted_at       timestamptz
);
-- Contador del codigo del proceso: una fila por tipo de proceso y anio (reinicia cada anio)
CREATE TABLE secuencias_codigo_proceso (
    tipo_proceso_id bigint   NOT NULL REFERENCES tipos_proceso(id),
    anio            smallint NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    ultimo          integer  NOT NULL CHECK (ultimo >= 1),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tipo_proceso_id, anio)
);

CREATE INDEX procesos_estado_idx ON procesos (estado_proceso_id);
CREATE INDEX procesos_macro_idx  ON procesos (estado_macro_id);

CREATE TABLE proceso_items (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id   bigint NOT NULL REFERENCES procesos(id),
    numero_linea smallint NOT NULL CHECK (numero_linea >= 1),
    cum          varchar(30)  NOT NULL,
    detalle      text NOT NULL,
    cantidad     bigint NOT NULL CHECK (cantidad > 0),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (proceso_id, numero_linea),
    UNIQUE (id, proceso_id)
);

CREATE TABLE asignaciones_proceso (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id    bigint NOT NULL REFERENCES procesos(id),
    user_id       bigint NOT NULL REFERENCES users(id),
    rol_id        bigint NOT NULL REFERENCES roles(id),
    fase_id       bigint NOT NULL REFERENCES fases(id),
    etapa_id      bigint REFERENCES etapas(id),
    actividad_id  bigint REFERENCES actividades(id),
    asignado_por  bigint NOT NULL REFERENCES users(id),
    fecha_inicio  timestamptz NOT NULL DEFAULT now(),
    fecha_fin     timestamptz,
    activo        boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE UNIQUE INDEX asignaciones_proceso_activa_uq
    ON asignaciones_proceso (proceso_id, user_id, rol_id, COALESCE(actividad_id, 0))
    WHERE activo;
CREATE INDEX asignaciones_proceso_user_idx ON asignaciones_proceso (user_id, activo);

CREATE TABLE historial_estados_proceso (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id        bigint NOT NULL REFERENCES procesos(id),
    transicion_id     bigint NOT NULL REFERENCES transiciones_proceso(id),
    estado_origen_id  bigint REFERENCES estados_proceso(id),
    estado_destino_id bigint NOT NULL REFERENCES estados_proceso(id),
    estado_macro_id   bigint NOT NULL REFERENCES estados_macro(id),
    user_id           bigint NOT NULL REFERENCES users(id),
    comentario        text,
    created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX historial_estados_proceso_idx ON historial_estados_proceso (proceso_id, created_at);

-- ---------------------------------------------------------------------
-- 4. PROVEEDORES, PUBLICACIONES, OFERTAS, DESIGNACIONES
-- ---------------------------------------------------------------------
CREATE TABLE proveedores (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc          varchar(13) UNIQUE CHECK (ruc ~ '^[0-9]{13}$'),
    razon_social varchar(250) NOT NULL,
    activo       boolean NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    deleted_at   timestamptz
);

CREATE TABLE proveedor_alias (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id bigint NOT NULL REFERENCES proveedores(id),
    alias        varchar(250) NOT NULL UNIQUE
);

CREATE TABLE precios_referenciales (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_item_id  bigint NOT NULL REFERENCES proceso_items(id),
    proveedor_id     bigint REFERENCES proveedores(id),
    fuente           varchar(80) NOT NULL,
    precio_unitario  numeric(14,4) NOT NULL CHECK (precio_unitario >= 0),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE publicaciones (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id        bigint NOT NULL REFERENCES procesos(id),
    ciclo             smallint NOT NULL DEFAULT 1,
    secuencia         smallint NOT NULL CHECK (secuencia >= 1),
    codigo_nc         varchar(60) NOT NULL,
    enlace            text,
    fecha_publicacion timestamptz NOT NULL,
    fecha_limite      timestamptz NOT NULL,
    observacion       text,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (proceso_id, ciclo, secuencia),
    UNIQUE (id, proceso_id),
    CHECK (fecha_limite >= fecha_publicacion)
);

CREATE TABLE ofertas (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id        bigint NOT NULL REFERENCES procesos(id),
    publicacion_id    bigint NOT NULL,
    proveedor_id      bigint NOT NULL REFERENCES proveedores(id),
    estado_oferta_id  bigint NOT NULL REFERENCES estados_oferta(id),
    fecha_presentacion timestamptz,
    observacion       text,
    creado_por        bigint NOT NULL REFERENCES users(id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    deleted_at        timestamptz,
    UNIQUE (publicacion_id, proveedor_id),
    UNIQUE (id, proceso_id),
    FOREIGN KEY (publicacion_id, proceso_id) REFERENCES publicaciones (id, proceso_id)
);

CREATE TABLE oferta_items (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id       bigint NOT NULL,
    oferta_id        bigint NOT NULL,
    proceso_item_id  bigint NOT NULL,
    precio_unitario  numeric(14,4) NOT NULL CHECK (precio_unitario >= 0),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (oferta_id, proceso_item_id),
    FOREIGN KEY (oferta_id, proceso_id)      REFERENCES ofertas (id, proceso_id),
    FOREIGN KEY (proceso_item_id, proceso_id) REFERENCES proceso_items (id, proceso_id)
);

CREATE TABLE historial_estados_oferta (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id         bigint NOT NULL REFERENCES ofertas(id),
    transicion_id     bigint NOT NULL REFERENCES transiciones_oferta(id),
    estado_origen_id  bigint REFERENCES estados_oferta(id),
    estado_destino_id bigint NOT NULL REFERENCES estados_oferta(id),
    user_id           bigint NOT NULL REFERENCES users(id),
    comentario        text,
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE oferta_evaluaciones (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id     bigint NOT NULL REFERENCES ofertas(id),
    evaluador_id  bigint NOT NULL REFERENCES users(id),
    cumple        boolean NOT NULL,
    seleccionada  boolean NOT NULL DEFAULT false,
    motivo        text,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE designaciones (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id          bigint NOT NULL REFERENCES procesos(id),
    tipo_designacion_id bigint NOT NULL REFERENCES tipos_designacion(id),
    monto_referencia    numeric(16,2),
    fecha               timestamptz,
    observacion         text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, proceso_id)
);

CREATE TABLE designacion_miembros (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designacion_id bigint NOT NULL REFERENCES designaciones(id),
    user_id        bigint NOT NULL REFERENCES users(id),
    rol_id         bigint NOT NULL REFERENCES roles(id),
    UNIQUE (designacion_id, user_id, rol_id)
);

-- ---------------------------------------------------------------------
-- 5. GESTION DOCUMENTAL
-- ---------------------------------------------------------------------
CREATE TABLE archivos (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disco           varchar(50)  NOT NULL,
    ruta            text NOT NULL,
    nombre_original varchar(255) NOT NULL,
    nombre_interno  varchar(255) NOT NULL UNIQUE,
    extension       varchar(10)  NOT NULL,
    mime            varchar(120) NOT NULL,
    tamano_bytes    bigint NOT NULL CHECK (tamano_bytes >= 0),
    hash_sha256     char(64) NOT NULL,
    user_id         bigint NOT NULL REFERENCES users(id),
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX archivos_hash_idx ON archivos (hash_sha256);

CREATE TABLE documentos (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id          bigint NOT NULL REFERENCES procesos(id),
    tipo_documento_id   bigint NOT NULL REFERENCES tipos_documento(id),
    etapa_id            bigint REFERENCES etapas(id),
    estado_documento_id bigint NOT NULL REFERENCES estados_documento(id),
    version_actual_id   bigint,
    titulo              varchar(250) NOT NULL,
    numero_documento    varchar(80),
    fecha_documento     date,
    oferta_id           bigint,
    designacion_id      bigint,
    creado_por          bigint NOT NULL REFERENCES users(id),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz,
    UNIQUE (id, proceso_id),
    FOREIGN KEY (oferta_id, proceso_id)      REFERENCES ofertas (id, proceso_id),
    FOREIGN KEY (designacion_id, proceso_id) REFERENCES designaciones (id, proceso_id)
);
CREATE INDEX documentos_proceso_idx ON documentos (proceso_id, estado_documento_id);

CREATE TABLE documento_versiones (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id   bigint NOT NULL REFERENCES documentos(id),
    numero_version integer NOT NULL CHECK (numero_version >= 1),
    archivo_id     bigint NOT NULL UNIQUE REFERENCES archivos(id),
    user_id        bigint NOT NULL REFERENCES users(id),
    comentario     text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (documento_id, numero_version),
    UNIQUE (id, documento_id)
);

-- la version actual debe pertenecer al mismo documento
ALTER TABLE documentos
    ADD CONSTRAINT documentos_version_actual_fk
    FOREIGN KEY (version_actual_id, id) REFERENCES documento_versiones (id, documento_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE historial_estados_documento (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id      bigint NOT NULL REFERENCES documentos(id),
    transicion_id     bigint NOT NULL REFERENCES transiciones_documento(id),
    estado_origen_id  bigint REFERENCES estados_documento(id),
    estado_destino_id bigint NOT NULL REFERENCES estados_documento(id),
    user_id           bigint NOT NULL REFERENCES users(id),
    comentario        text,
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE asignaciones_documento (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id     bigint NOT NULL REFERENCES documentos(id),
    user_id          bigint NOT NULL REFERENCES users(id),
    tarea            varchar(20) NOT NULL CHECK (tarea IN ('revisar','corregir')),
    asignado_por     bigint NOT NULL REFERENCES users(id),
    fecha_asignacion timestamptz NOT NULL DEFAULT now(),
    fecha_fin        timestamptz,
    activo           boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX asignaciones_documento_activa_uq
    ON asignaciones_documento (documento_id, user_id, tarea) WHERE activo;

CREATE TABLE revisiones (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_version_id bigint NOT NULL REFERENCES documento_versiones(id),
    numero_revision      integer NOT NULL CHECK (numero_revision >= 1),
    revisor_id           bigint NOT NULL REFERENCES users(id),
    resultado            varchar(20) NOT NULL CHECK (resultado IN ('aprobada','con_observaciones')),
    fecha_inicio         timestamptz NOT NULL DEFAULT now(),
    fecha_fin            timestamptz,
