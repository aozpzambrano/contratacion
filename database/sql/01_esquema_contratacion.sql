-- El usuario tiene un rol activo con el permiso y (si hay fase) el rol opera en ella
CREATE FUNCTION usuario_puede(p_user bigint, p_permiso bigint, p_fase bigint) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1
          FROM usuario_rol ur
          JOIN roles r        ON r.id = ur.rol_id AND r.activo
          JOIN rol_permiso rp ON rp.rol_id = r.id AND rp.permiso_id = p_permiso
          JOIN permisos p     ON p.id = rp.permiso_id AND p.activo
          JOIN users u        ON u.id = ur.user_id AND u.activo
         WHERE ur.user_id = p_user
           AND (p_fase IS NULL OR EXISTS (
                SELECT 1 FROM rol_fase rf WHERE rf.rol_id = r.id AND rf.fase_id = p_fase))
    )
$$;

