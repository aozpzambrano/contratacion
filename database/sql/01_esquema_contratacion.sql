-- Tablas historicas: no se permite UPDATE ni DELETE
CREATE FUNCTION fn_bloquear_modificacion() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'La tabla % es historica: no admite % de registros', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'integrity_constraint_violation';
END $$;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'auditoria','archivos','documento_versiones','revisiones','observaciones',
        'correcciones','aprobaciones','legalizaciones','oferta_evaluaciones','devoluciones',
        'historial_estados_proceso','historial_estados_documento','historial_estados_oferta']
    LOOP
        EXECUTE format(
            'CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON %I
             FOR EACH ROW EXECUTE FUNCTION fn_bloquear_modificacion()',
            t || '_inmutable', t);
    END LOOP;
END $$;

-- El estado solo puede cambiar mediante aplicar_transicion_*
CREATE FUNCTION fn_proteger_estado() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE c text;
BEGIN
    FOREACH c IN ARRAY TG_ARGV LOOP
        IF to_jsonb(NEW)->>c IS DISTINCT FROM to_jsonb(OLD)->>c
           AND COALESCE(current_setting('app.transicion_en_curso', true), '') <> TG_TABLE_NAME THEN
            RAISE EXCEPTION 'La columna %.% solo cambia mediante una transicion autorizada', TG_TABLE_NAME, c
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END LOOP;
    RETURN NEW;
END $$;

