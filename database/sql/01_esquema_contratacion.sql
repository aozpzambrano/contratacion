-- Reglas declarativas de transiciones de proceso. Devuelve el error o NULL.
CREATE FUNCTION fn_validar_proceso(p_id bigint, p_reglas jsonb) RETURNS text
LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_p procesos%ROWTYPE; r record;
    v_pubs int; v_ofs int; v_min int; v_max int;
BEGIN
    SELECT * INTO v_p FROM procesos WHERE id = p_id;
    SELECT count(*) INTO v_pubs FROM publicaciones WHERE proceso_id = p_id AND ciclo = v_p.ciclo;
    SELECT count(*) INTO v_ofs
      FROM ofertas o JOIN publicaciones pu ON pu.id = o.publicacion_id
     WHERE o.proceso_id = p_id AND pu.ciclo = v_p.ciclo AND o.deleted_at IS NULL;
    v_min := COALESCE(parametro_entero('minimo_proformas'), 3);
    v_max := COALESCE(parametro_entero('maximo_publicaciones'), 2);

    FOR r IN SELECT key, value FROM jsonb_each(p_reglas) LOOP
        CASE r.key
        WHEN 'incrementa_ciclo' THEN NULL;
        WHEN 'sin_observaciones_pendientes' THEN
            IF EXISTS (SELECT 1 FROM observaciones ob
                        JOIN revisiones rv ON rv.id = ob.revision_id
                        JOIN documento_versiones dv ON dv.id = rv.documento_version_id
                        JOIN documentos d ON d.id = dv.documento_id
                       WHERE d.proceso_id = p_id AND d.deleted_at IS NULL AND ob.tipo = 'observacion'
                         AND NOT EXISTS (SELECT 1 FROM correcciones c WHERE c.observacion_id = ob.id)) THEN
                RETURN 'Existen observaciones pendientes de correccion';
            END IF;
        WHEN 'requiere_codigo' THEN
            IF v_p.codigo IS NULL THEN RETURN 'El proceso debe tener codigo antes de esta transicion'; END IF;
        WHEN 'requiere_responsable' THEN
            IF NOT EXISTS (SELECT 1 FROM asignaciones_proceso a JOIN roles ro ON ro.id = a.rol_id
                            WHERE a.proceso_id = p_id AND a.activo AND ro.codigo = r.value #>> '{}') THEN
                RETURN format('El proceso no tiene responsable asignado con el rol %s', r.value #>> '{}');
            END IF;
        WHEN 'requiere_publicacion' THEN
            IF v_pubs = 0 THEN RETURN 'No existe una publicacion registrada en el ciclo actual'; END IF;
        WHEN 'publicaciones_menor_a' THEN
            IF v_pubs >= COALESCE(parametro_entero(r.value #>> '{}'), v_max) THEN
                RETURN 'Ya se alcanzo el maximo de publicaciones'; END IF;
        WHEN 'ofertas_menor_a' THEN
            IF v_ofs >= COALESCE(parametro_entero(r.value #>> '{}'), v_min) THEN
                RETURN 'Ya se alcanzo el numero de ofertas requerido'; END IF;
        WHEN 'ofertas_para_comision' THEN
            IF NOT (v_ofs >= v_min OR (v_pubs >= v_max AND v_ofs >= 1)) THEN
                RETURN 'No se cumple el numero de ofertas para enviar a comision'; END IF;
        WHEN 'sin_ofertas_publicaciones_agotadas' THEN
            IF NOT (v_pubs >= v_max AND v_ofs = 0) THEN
                RETURN 'Solo procede la devolucion sin ofertas con las publicaciones agotadas'; END IF;
        WHEN 'requiere_devolucion_registrada' THEN
            IF NOT EXISTS (SELECT 1 FROM devoluciones WHERE proceso_id = p_id AND ciclo = v_p.ciclo) THEN
                RETURN 'Debe registrar la devolucion (memorando) antes de la transicion'; END IF;
        WHEN 'devolucion_permite_reapertura' THEN
            IF NOT COALESCE((SELECT reapertura_permitida FROM devoluciones
                              WHERE proceso_id = p_id AND ciclo = v_p.ciclo
                              ORDER BY id DESC LIMIT 1), false) THEN
                RETURN 'La devolucion no autoriza la reapertura del proceso'; END IF;
        WHEN 'requiere_designacion' THEN
            IF NOT EXISTS (SELECT 1 FROM designaciones WHERE proceso_id = p_id) THEN
                RETURN 'No existe una designacion registrada'; END IF;
        WHEN 'requiere_oferta_seleccionada' THEN
            IF NOT EXISTS (SELECT 1 FROM ofertas o JOIN estados_oferta eo ON eo.id = o.estado_oferta_id
                            WHERE o.proceso_id = p_id AND o.deleted_at IS NULL AND eo.resultado = 'favorable') THEN
                RETURN 'No existe una oferta seleccionada'; END IF;
        WHEN 'requiere_orden_compra' THEN
            IF NOT EXISTS (SELECT 1 FROM ordenes_compra WHERE proceso_id = p_id) THEN
                RETURN 'No existe una orden de compra registrada'; END IF;
        ELSE
            RETURN format('Regla de validacion desconocida: %s', r.key);
        END CASE;
    END LOOP;
    RETURN NULL;
END $$;

-- Aplica una transicion de proceso: autoriza, valida, cambia estado, registra historial
-- El codigo solo se asigna con asignar_codigo_proceso() y no se puede cambiar despues
CREATE FUNCTION fn_proteger_codigo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.codigo IS DISTINCT FROM OLD.codigo THEN
        IF OLD.codigo IS NOT NULL THEN
            RAISE EXCEPTION 'El codigo del proceso no puede modificarse una vez asignado';
        END IF;
        IF COALESCE(current_setting('app.asignando_codigo', true), '') <> 'on' THEN
            RAISE EXCEPTION 'El codigo del proceso solo se asigna con asignar_codigo_proceso()';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER procesos_proteger_codigo BEFORE UPDATE OF codigo ON procesos
    FOR EACH ROW EXECUTE FUNCTION fn_proteger_codigo();

-- Genera el codigo: <prefijo del tipo>-<prefijo institucional>-<anio>-<numero>, p. ej. PE-AILEP-2026-001.
-- El anio es el del momento de generarlo (zona horaria del parametro zona_horaria); el numero reinicia cada anio.
CREATE FUNCTION asignar_codigo_proceso(p_proceso_id bigint, p_user_id bigint) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
    v_p procesos%ROWTYPE; v_ep estados_proceso%ROWTYPE; v_perm permisos%ROWTYPE;
    v_fase bigint; v_prefijo text; v_anio int; v_n int; v_dig int; v_codigo text;
BEGIN
    SELECT * INTO v_p FROM procesos WHERE id = p_proceso_id AND deleted_at IS NULL FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'El proceso no existe'; END IF;

    SELECT * INTO v_perm FROM permisos WHERE codigo = 'procesos.asignar_codigo' AND activo;
    SELECT fase_id INTO v_fase FROM estados_macro WHERE id = v_p.estado_macro_id;
    IF v_perm.id IS NULL OR NOT usuario_puede(p_user_id, v_perm.id, v_fase) THEN
        RAISE EXCEPTION 'El usuario no tiene el permiso procesos.asignar_codigo en esta fase'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF v_perm.requiere_asignacion AND NOT EXISTS (
        SELECT 1 FROM asignaciones_proceso a
         WHERE a.proceso_id = v_p.id AND a.user_id = p_user_id AND a.activo) THEN
        RAISE EXCEPTION 'El usuario no esta asignado a este proceso'
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    IF v_p.codigo IS NOT NULL THEN
        RAISE EXCEPTION 'El proceso ya tiene codigo (%)', v_p.codigo;
    END IF;
    SELECT * INTO v_ep FROM estados_proceso WHERE id = v_p.estado_proceso_id;
    IF NOT v_ep.permite_asignar_codigo THEN
        RAISE EXCEPTION 'En el estado "%" no se puede asignar el codigo del proceso', v_ep.nombre;
    END IF;

    v_anio := EXTRACT(year FROM now() AT TIME ZONE COALESCE(parametro_texto('zona_horaria'), 'America/Guayaquil'))::int;
    v_dig  := COALESCE(parametro_entero('digitos_codigo_proceso'), 3);
    SELECT prefijo INTO v_prefijo FROM tipos_proceso WHERE id = v_p.tipo_proceso_id;

    -- El upsert bloquea la fila del contador: dos analistas no obtienen el mismo numero
    INSERT INTO secuencias_codigo_proceso (tipo_proceso_id, anio, ultimo)
    VALUES (v_p.tipo_proceso_id, v_anio, 1)
    ON CONFLICT (tipo_proceso_id, anio)
    DO UPDATE SET ultimo = secuencias_codigo_proceso.ultimo + 1, updated_at = now()
    RETURNING ultimo INTO v_n;

    v_codigo := concat_ws('-', v_prefijo, NULLIF(parametro_texto('prefijo_institucion'), ''), v_anio::text,
                          repeat('0', GREATEST(v_dig - length(v_n::text), 0)) || v_n::text);

    PERFORM set_config('app.asignando_codigo', 'on', true);
    UPDATE procesos SET codigo = v_codigo, updated_at = now() WHERE id = v_p.id;
    PERFORM set_config('app.asignando_codigo', '', true);

    INSERT INTO auditoria (user_id, evento, entidad, entidad_id, valores_nuevos)
    VALUES (p_user_id, 'proceso.codigo_asignado', 'procesos', v_p.id, jsonb_build_object('codigo', v_codigo));
    RETURN v_codigo;
END $$;

CREATE FUNCTION aplicar_transicion_proceso(
    p_proceso_id bigint, p_codigo text, p_user_id bigint, p_comentario text DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql AS $$
DECLARE
    v_p procesos%ROWTYPE; v_t transiciones_proceso%ROWTYPE; v_perm permisos%ROWTYPE;
    v_fase bigint; v_err text; v_falta text; v_hist bigint;
BEGIN
    SELECT * INTO v_p FROM procesos WHERE id = p_proceso_id AND deleted_at IS NULL FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'El proceso % no existe', p_proceso_id; END IF;

    SELECT * INTO v_t FROM transiciones_proceso
     WHERE estado_origen_id = v_p.estado_proceso_id AND codigo = p_codigo AND activo;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La transicion "%" no esta permitida desde el estado actual', p_codigo;
    END IF;

    SELECT * INTO v_perm FROM permisos WHERE id = v_t.permiso_id;
    SELECT fase_id INTO v_fase FROM estados_macro WHERE id = v_p.estado_macro_id;

    IF NOT usuario_puede(p_user_id, v_t.permiso_id, v_fase) THEN
        RAISE EXCEPTION 'El usuario no tiene el permiso % en esta fase', v_perm.codigo
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF v_perm.requiere_asignacion AND NOT EXISTS (
        SELECT 1 FROM asignaciones_proceso a
         WHERE a.proceso_id = v_p.id AND a.user_id = p_user_id AND a.activo) THEN
        RAISE EXCEPTION 'El usuario no esta asignado a este proceso'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF v_t.requiere_comentario AND COALESCE(btrim(p_comentario), '') = '' THEN
        RAISE EXCEPTION 'La transicion "%" exige un comentario', p_codigo;
    END IF;

    SELECT string_agg(td.nombre, ', ') INTO v_falta
      FROM transicion_proceso_requisitos rq
      JOIN tipos_documento td   ON td.id = rq.tipo_documento_id
      JOIN estados_documento em ON em.id = rq.estado_documento_minimo_id
     WHERE rq.transicion_id = v_t.id
       AND NOT EXISTS (
            SELECT 1 FROM documentos d JOIN estados_documento ed ON ed.id = d.estado_documento_id
             WHERE d.proceso_id = v_p.id AND d.tipo_documento_id = rq.tipo_documento_id
               AND d.deleted_at IS NULL AND ed.grupo <> 'anulado' AND ed.orden >= em.orden);
    IF v_falta IS NOT NULL THEN
        RAISE EXCEPTION 'Faltan documentos requeridos: %', v_falta;
    END IF;

    v_err := fn_validar_proceso(v_p.id, v_t.validaciones);
    IF v_err IS NOT NULL THEN RAISE EXCEPTION '%', v_err; END IF;

    PERFORM set_config('app.transicion_en_curso', 'procesos', true);
    UPDATE procesos
       SET estado_proceso_id = v_t.estado_destino_id,
           estado_macro_id   = COALESCE(v_t.estado_macro_destino_id, estado_macro_id),
           ciclo             = CASE WHEN COALESCE((v_t.validaciones->>'incrementa_ciclo')::boolean, false)
                                    THEN ciclo + 1 ELSE ciclo END,
           updated_at        = now()
     WHERE id = v_p.id;
    PERFORM set_config('app.transicion_en_curso', '', true);

    INSERT INTO historial_estados_proceso
        (proceso_id, transicion_id, estado_origen_id, estado_destino_id, estado_macro_id, user_id, comentario)
    SELECT v_p.id, v_t.id, v_p.estado_proceso_id, v_t.estado_destino_id, pr.estado_macro_id, p_user_id, p_comentario
      FROM procesos pr WHERE pr.id = v_p.id
    RETURNING id INTO v_hist;

    INSERT INTO auditoria (user_id, evento, entidad, entidad_id, valores_anteriores, valores_nuevos)
    VALUES (p_user_id, 'proceso.transicion', 'procesos', v_p.id,
            jsonb_build_object('estado_proceso_id', v_p.estado_proceso_id),
            jsonb_build_object('estado_proceso_id', v_t.estado_destino_id, 'transicion', v_t.codigo));
    RETURN v_hist;
END $$;

-- Transiciones de documento
CREATE FUNCTION aplicar_transicion_documento(
    p_documento_id bigint, p_codigo text, p_user_id bigint, p_comentario text DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql AS $$
DECLARE
    v_d documentos%ROWTYPE; v_t transiciones_documento%ROWTYPE; v_perm permisos%ROWTYPE;
    v_fase bigint; v_hist bigint;
BEGIN
    SELECT * INTO v_d FROM documentos WHERE id = p_documento_id AND deleted_at IS NULL FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'El documento % no existe', p_documento_id; END IF;

    SELECT * INTO v_t FROM transiciones_documento
     WHERE estado_origen_id = v_d.estado_documento_id AND codigo = p_codigo AND activo;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La transicion "%" no esta permitida desde el estado actual del documento', p_codigo;
    END IF;

    SELECT * INTO v_perm FROM permisos WHERE id = v_t.permiso_id;
    SELECT em.fase_id INTO v_fase FROM procesos p JOIN estados_macro em ON em.id = p.estado_macro_id
     WHERE p.id = v_d.proceso_id;

    IF NOT usuario_puede(p_user_id, v_t.permiso_id, v_fase) THEN
        RAISE EXCEPTION 'El usuario no tiene el permiso % en esta fase', v_perm.codigo
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF v_perm.requiere_asignacion AND NOT EXISTS (
        SELECT 1 FROM asignaciones_documento a
         WHERE a.documento_id = v_d.id AND a.user_id = p_user_id AND a.activo) THEN
        RAISE EXCEPTION 'El documento no esta asignado al usuario'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF v_t.requiere_comentario AND COALESCE(btrim(p_comentario), '') = '' THEN
        RAISE EXCEPTION 'La transicion "%" exige un comentario', p_codigo;
    END IF;
    IF COALESCE((v_t.validaciones->>'tipo_sin_revision')::boolean, false)
       AND (SELECT requiere_revision FROM tipos_documento WHERE id = v_d.tipo_documento_id) THEN
        RAISE EXCEPTION 'Este tipo de documento exige revision';
    END IF;
    IF COALESCE((v_t.validaciones->>'requiere_version')::boolean, false) AND v_d.version_actual_id IS NULL THEN
        RAISE EXCEPTION 'El documento no tiene ninguna version cargada';
    END IF;

    PERFORM set_config('app.transicion_en_curso', 'documentos', true);
    UPDATE documentos SET estado_documento_id = v_t.estado_destino_id, updated_at = now() WHERE id = v_d.id;
    PERFORM set_config('app.transicion_en_curso', '', true);

    INSERT INTO historial_estados_documento
        (documento_id, transicion_id, estado_origen_id, estado_destino_id, user_id, comentario)
    VALUES (v_d.id, v_t.id, v_d.estado_documento_id, v_t.estado_destino_id, p_user_id, p_comentario)
    RETURNING id INTO v_hist;
    RETURN v_hist;
END $$;

