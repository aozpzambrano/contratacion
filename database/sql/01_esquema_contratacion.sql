CREATE VIEW v_ofertas_totales AS
SELECT o.id AS oferta_id, o.proceso_id, o.publicacion_id, o.proveedor_id,
       count(oi.id) AS lineas,
       COALESCE(sum(oi.precio_unitario * pi.cantidad), 0)::numeric(16,2) AS total
  FROM ofertas o
  LEFT JOIN oferta_items oi  ON oi.oferta_id = o.id
  LEFT JOIN proceso_items pi ON pi.id = oi.proceso_item_id
 WHERE o.deleted_at IS NULL
 GROUP BY o.id;

CREATE VIEW v_procesos AS
SELECT p.id AS proceso_id, p.codigo, EXTRACT(year FROM p.created_at AT TIME ZONE 'America/Guayaquil')::int AS anio_creacion,
       p.descripcion_producto, p.codigo_cpc, p.ciclo,
       tp.nombre AS tipo_proceso,
       f.nombre  AS fase, em.codigo AS estado_macro_codigo, em.nombre AS estado_macro,
       ep.codigo AS estado_codigo, ep.nombre AS estado_operativo,
       (SELECT string_agg(DISTINCT u.name, ', ') FROM asignaciones_proceso a
          JOIN roles r ON r.id = a.rol_id JOIN users u ON u.id = a.user_id
         WHERE a.proceso_id = p.id AND a.activo AND r.codigo = 'COMPRAS_ANALISTA') AS analista_responsable,
       (SELECT string_agg(DISTINCT u.name, ', ') FROM asignaciones_proceso a
          JOIN roles r ON r.id = a.rol_id JOIN users u ON u.id = a.user_id
         WHERE a.proceso_id = p.id AND a.activo AND r.codigo = 'UNIDAD_REQUIRENTE') AS unidad_requirente,
       (SELECT count(*) FROM proceso_items pi WHERE pi.proceso_id = p.id) AS lineas,
       (SELECT count(*) FROM publicaciones pu WHERE pu.proceso_id = p.id AND pu.ciclo = p.ciclo) AS publicaciones,
       (SELECT count(*) FROM ofertas o JOIN publicaciones pu ON pu.id = o.publicacion_id
         WHERE o.proceso_id = p.id AND pu.ciclo = p.ciclo AND o.deleted_at IS NULL) AS ofertas,
       (SELECT max(t.total) FROM v_ofertas_totales t JOIN publicaciones pu ON pu.id = t.publicacion_id
         WHERE t.proceso_id = p.id AND pu.ciclo = p.ciclo) AS monto_maximo_ofertas,
       p.observacion, p.created_at, p.updated_at
  FROM procesos p
  JOIN tipos_proceso tp   ON tp.id = p.tipo_proceso_id
  JOIN estados_macro em   ON em.id = p.estado_macro_id
  LEFT JOIN fases f       ON f.id = em.fase_id
  JOIN estados_proceso ep ON ep.id = p.estado_proceso_id
 WHERE p.deleted_at IS NULL;

CREATE VIEW v_ofertas AS
SELECT o.id AS oferta_id, p.id AS proceso_id, p.codigo AS proceso, pu.ciclo, pu.secuencia AS publicacion,
       pu.codigo_nc, pr.id AS proveedor_id, pr.ruc, pr.razon_social,
       eo.nombre AS estado, eo.resultado, o.fecha_presentacion, t.total, t.lineas, o.observacion
  FROM ofertas o
  JOIN procesos p        ON p.id = o.proceso_id
  JOIN publicaciones pu  ON pu.id = o.publicacion_id
  JOIN proveedores pr    ON pr.id = o.proveedor_id
  JOIN estados_oferta eo ON eo.id = o.estado_oferta_id
  LEFT JOIN v_ofertas_totales t ON t.oferta_id = o.id
 WHERE o.deleted_at IS NULL;

CREATE VIEW v_ofertas_por_proveedor AS
SELECT pr.id AS proveedor_id, pr.ruc, pr.razon_social,
       count(o.id) AS ofertas,
       count(DISTINCT o.proceso_id) AS procesos,
       count(*) FILTER (WHERE eo.resultado = 'favorable')    AS favorables,
       count(*) FILTER (WHERE eo.resultado = 'desfavorable') AS desfavorables
  FROM proveedores pr
  LEFT JOIN ofertas o         ON o.proveedor_id = pr.id AND o.deleted_at IS NULL
  LEFT JOIN estados_oferta eo ON eo.id = o.estado_oferta_id
 WHERE pr.deleted_at IS NULL
 GROUP BY pr.id;

-- Equivalente a la hoja del Excel: una fila por linea de producto
CREATE VIEW v_matriz_contratacion AS
SELECT p.id AS proceso_id, p.codigo, p.descripcion_producto, p.codigo_cpc, p.ciclo,
       pi.numero_linea, pi.cum, pi.detalle AS producto, pi.cantidad,
       vp.estado_macro, vp.estado_operativo, vp.analista_responsable, vp.unidad_requirente,
       ref.precio_referencial,
       ofe.ofertas_recibidas, ofe.mejor_precio_unitario, ofe.mejor_proveedor,
       pub1.codigo_nc AS pub1_nc, pub1.enlace AS pub1_enlace,
       pub1.fecha_publicacion AS pub1_fecha, pub1.fecha_limite AS pub1_limite, pub1.ofertas AS pub1_ofertas,
       pub2.codigo_nc AS pub2_nc, pub2.enlace AS pub2_enlace,
       pub2.fecha_publicacion AS pub2_fecha, pub2.fecha_limite AS pub2_limite, pub2.ofertas AS pub2_ofertas,
       td.nombre AS tipo_designacion_registrada,
       td2.nombre AS tipo_designacion_sugerida,
       oc.fecha_orden, oc.numero AS orden_compra, oc.ruc AS oc_ruc, oc.razon_social AS oc_proveedor,
       oc.representante_legal, oc.administrador_nombre, oc.administrador_correo,
       ent.entregas, ent.cantidad_entregada,
       p.observacion
  FROM procesos p
  JOIN proceso_items pi ON pi.proceso_id = p.id
  JOIN v_procesos vp    ON vp.proceso_id = p.id
  LEFT JOIN LATERAL (
        SELECT min(r.precio_unitario) AS precio_referencial
          FROM precios_referenciales r WHERE r.proceso_item_id = pi.id) ref ON true
  LEFT JOIN LATERAL (
        SELECT count(*) AS ofertas_recibidas,
               min(oi.precio_unitario) AS mejor_precio_unitario,
               (array_agg(pr.razon_social ORDER BY oi.precio_unitario))[1] AS mejor_proveedor
          FROM oferta_items oi
          JOIN ofertas o ON o.id = oi.oferta_id AND o.deleted_at IS NULL
          JOIN publicaciones pu ON pu.id = o.publicacion_id AND pu.ciclo = p.ciclo
          JOIN proveedores pr ON pr.id = o.proveedor_id
         WHERE oi.proceso_item_id = pi.id) ofe ON true
  LEFT JOIN LATERAL (
        SELECT pu.*, (SELECT count(*) FROM ofertas o WHERE o.publicacion_id = pu.id AND o.deleted_at IS NULL) AS ofertas
          FROM publicaciones pu WHERE pu.proceso_id = p.id AND pu.ciclo = p.ciclo AND pu.secuencia = 1) pub1 ON true
  LEFT JOIN LATERAL (
        SELECT pu.*, (SELECT count(*) FROM ofertas o WHERE o.publicacion_id = pu.id AND o.deleted_at IS NULL) AS ofertas
          FROM publicaciones pu WHERE pu.proceso_id = p.id AND pu.ciclo = p.ciclo AND pu.secuencia = 2) pub2 ON true
  LEFT JOIN LATERAL (
        SELECT d.tipo_designacion_id FROM designaciones d
         WHERE d.proceso_id = p.id ORDER BY d.id DESC LIMIT 1) des ON true
  LEFT JOIN tipos_designacion td ON td.id = des.tipo_designacion_id
  LEFT JOIN tipos_designacion td2 ON td2.id = tipo_designacion_sugerido(vp.monto_maximo_ofertas)
  LEFT JOIN LATERAL (
        SELECT o.fecha_orden, o.numero, o.representante_legal, o.administrador_nombre, o.administrador_correo,
               pr.ruc, pr.razon_social
          FROM ordenes_compra o JOIN proveedores pr ON pr.id = o.proveedor_id
         WHERE o.proceso_id = p.id ORDER BY o.id DESC LIMIT 1) oc ON true
  LEFT JOIN LATERAL (
        SELECT count(DISTINCT ei.entrega_id) AS entregas, COALESCE(sum(ei.cantidad), 0) AS cantidad_entregada
          FROM entrega_items ei WHERE ei.proceso_item_id = pi.id) ent ON true
 WHERE p.deleted_at IS NULL;

CREATE VIEW v_documentos AS
SELECT d.id AS documento_id, p.id AS proceso_id, p.codigo AS proceso,
       f.nombre AS fase, e.nombre AS etapa, td.nombre AS tipo_documento,
       ed.nombre AS estado, ed.grupo AS estado_grupo,
       d.titulo, d.numero_documento, d.fecha_documento,
       dv.numero_version AS version_actual, a.nombre_original AS archivo,
       uc.name AS creado_por, d.created_at,
       (SELECT count(*) FROM documento_versiones x WHERE x.documento_id = d.id) AS versiones,
       (SELECT count(*) FROM revisiones r JOIN documento_versiones x ON x.id = r.documento_version_id
         WHERE x.documento_id = d.id) AS revisiones,
       (SELECT max(ap.created_at) FROM aprobaciones ap JOIN documento_versiones x ON x.id = ap.documento_version_id
         WHERE x.documento_id = d.id) AS fecha_aprobacion,
       (SELECT max(lg.created_at) FROM legalizaciones lg JOIN documento_versiones x ON x.id = lg.documento_version_id
         WHERE x.documento_id = d.id) AS fecha_legalizacion,
       (SELECT string_agg(DISTINCT u.name, ', ') FROM asignaciones_documento ad
          JOIN users u ON u.id = ad.user_id WHERE ad.documento_id = d.id AND ad.activo) AS asignados
  FROM documentos d
  JOIN procesos p          ON p.id = d.proceso_id
  JOIN tipos_documento td  ON td.id = d.tipo_documento_id
  JOIN estados_documento ed ON ed.id = d.estado_documento_id
  JOIN users uc            ON uc.id = d.creado_por
  LEFT JOIN etapas e       ON e.id = d.etapa_id
  LEFT JOIN fases f        ON f.id = e.fase_id
  LEFT JOIN documento_versiones dv ON dv.id = d.version_actual_id
  LEFT JOIN archivos a     ON a.id = dv.archivo_id
 WHERE d.deleted_at IS NULL;

CREATE VIEW v_documentos_pendientes    AS SELECT * FROM v_documentos WHERE estado_grupo = 'pendiente';
CREATE VIEW v_documentos_en_correccion AS SELECT * FROM v_documentos WHERE estado_grupo = 'en_correccion';
CREATE VIEW v_documentos_aprobados     AS SELECT * FROM v_documentos WHERE estado_grupo = 'aprobado';

CREATE VIEW v_historial_revisiones AS
SELECT r.id AS revision_id, d.proceso_id, d.id AS documento_id, d.titulo,
       dv.numero_version, r.numero_revision, u.name AS revisor, r.resultado,
       r.fecha_inicio, r.fecha_fin,
       (SELECT count(*) FROM observaciones o WHERE o.revision_id = r.id) AS observaciones,
       a.nombre_original AS archivo_revisado
  FROM revisiones r
  JOIN documento_versiones dv ON dv.id = r.documento_version_id
  JOIN documentos d           ON d.id = dv.documento_id
  JOIN archivos a             ON a.id = dv.archivo_id
  JOIN users u                ON u.id = r.revisor_id;

CREATE VIEW v_historial_observaciones AS
SELECT o.id AS observacion_id, d.proceso_id, d.id AS documento_id, d.titulo,
       dv.numero_version, r.numero_revision, o.tipo, o.texto, u.name AS registrada_por, o.created_at,
       EXISTS (SELECT 1 FROM correcciones c WHERE c.observacion_id = o.id) AS corregida
  FROM observaciones o
  JOIN revisiones r           ON r.id = o.revision_id
  JOIN documento_versiones dv ON dv.id = r.documento_version_id
  JOIN documentos d           ON d.id = dv.documento_id
  JOIN users u                ON u.id = o.user_id;

CREATE VIEW v_historial_correcciones AS
SELECT c.id AS correccion_id, d.proceso_id, d.id AS documento_id, d.titulo,
       o.texto AS observacion, c.descripcion AS correccion,
       dv.numero_version AS version_corregida, u.name AS corregido_por, c.created_at
  FROM correcciones c
  JOIN observaciones o        ON o.id = c.observacion_id
  JOIN documento_versiones dv ON dv.id = c.documento_version_id
  JOIN documentos d           ON d.id = dv.documento_id
  JOIN users u                ON u.id = c.user_id;

CREATE VIEW v_tiempos_revision AS
SELECT d.id AS documento_id, d.proceso_id, d.titulo,
       min(dv.created_at) AS primera_version,
       (SELECT min(r.fecha_inicio) FROM revisiones r JOIN documento_versiones x ON x.id = r.documento_version_id
         WHERE x.documento_id = d.id) AS primera_revision,
       (SELECT min(ap.created_at) FROM aprobaciones ap JOIN documento_versiones x ON x.id = ap.documento_version_id
         WHERE x.documento_id = d.id) AS aprobacion,
       round(extract(epoch FROM (
         (SELECT min(ap.created_at) FROM aprobaciones ap JOIN documento_versiones x ON x.id = ap.documento_version_id
           WHERE x.documento_id = d.id) - min(dv.created_at))) / 3600.0, 2) AS horas_hasta_aprobacion,
       count(dv.id) AS versiones
  FROM documentos d
  JOIN documento_versiones dv ON dv.documento_id = d.id
 WHERE d.deleted_at IS NULL
 GROUP BY d.id;

COMMIT;
